export function localeForLanguage(lang: AppLanguage): string {
  switch (lang) {
    case 'es':
      return 'es-ES';
    case 'ca':
      return 'ca-ES';
    case 'pt':
      return 'pt-PT';
    case 'de':
      return 'de-DE';
    case 'fr':
      return 'fr-FR';
    case 'it':
      return 'it-IT';
    case 'nl':
      return 'nl-NL';
    case 'fi':
      return 'fi-FI';
    case 'sv':
      return 'sv-SE';
    case 'da':
      return 'da-DK';
    case 'hu':
      return 'hu-HU';
    case 'pl':
      return 'pl-PL';
    case 'ru':
      return 'ru-RU';
    case 'tr':
      return 'tr-TR';
    case 'el':
      return 'el-GR';
    case 'ar':
      return 'ar-SA';
    case 'zh':
      return 'zh-CN';
    case 'ja':
      return 'ja-JP';
    case 'ko':
      return 'ko-KR';
    default:
      return 'en-US';
  }
}

export function translate(
  lang: AppLanguage,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = catalogs[lang]?.[key] ?? catalogs.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(vars[name] ?? `{${name}}`),
  );
}
